"""Print random ``KEY=VALUE`` lines for the local NetBox lab (append them to ``.env``).

    uv run python -m netsec_check.netbox.secrets >> .env

Values are alphanumeric so docker compose interpolation never sees a ``$``.
"""

from __future__ import annotations

import secrets
import string

ALPHABET = string.ascii_letters + string.digits


def _random(length: int) -> str:
    return "".join(secrets.choice(ALPHABET) for _ in range(length))


def lab_secrets() -> dict[str, str]:
    key, secret = _random(12), _random(40)
    return {
        "NETBOX_DB_PASSWORD": _random(32),
        "NETBOX_REDIS_PASSWORD": _random(32),
        "NETBOX_SECRET_KEY": _random(64),
        "NETBOX_API_TOKEN_PEPPER": _random(64),
        "NETBOX_SUPERUSER_PASSWORD": _random(24),
        "NETBOX_API_KEY": key,
        "NETBOX_API_SECRET": secret,
        "NETBOX_TOKEN": f"nbt_{key}.{secret}",
    }


if __name__ == "__main__":
    print("\n# Local NetBox lab (generated by netsec_check.netbox.secrets)")
    print("NETBOX_URL=http://127.0.0.1:8000")
    for name, value in lab_secrets().items():
        print(f"{name}={value}")
